#!/usr/bin/env node
// Collects the Google place IDs of every 24 Hour Fitness club in Southern
// California and writes them to a SQL migration.
//
// Only place IDs are kept: Google's terms allow storing place IDs
// indefinitely, but not business names, addresses or (beyond 30 days)
// coordinates. Names and coordinates are used here only to filter results.
//
// Usage: GOOGLE_MAPS_API_KEY=... node scripts/fetch-24hf-socal.mjs [output.sql]

import { writeFileSync } from "node:fs";

// Mexican border to just north of Santa Clarita; Arizona border to west of
// Oxnard. Excludes Santa Barbara and the Antelope Valley.
const REGION = { south: 32.53, north: 34.5, west: -119.5, east: -114.13 };
const START_TILE_DEG = 0.5;
const MIN_TILE_DEG = 0.05;
const PAGE_CAP = 60; // Text Search returns at most 3 pages of 20.
const QUERY = "24 Hour Fitness";
const BRAND = /^24 Hour Fitness\b/i;
const FIELDS = "places.id,places.displayName,places.location,places.businessStatus,nextPageToken";

const apiKey = process.env.GOOGLE_MAPS_API_KEY;
if (!apiKey) {
  console.error("Set GOOGLE_MAPS_API_KEY.");
  process.exit(1);
}
const output = process.argv[2] ?? "supabase/migrations/20261109000000_partner_gyms.sql";

let calls = 0;

async function searchTile(tile) {
  const places = [];
  let pageToken;
  do {
    calls += 1;
    const res = await fetch("https://places.googleapis.com/v1/places:searchText", {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-Goog-Api-Key": apiKey, "X-Goog-FieldMask": FIELDS },
      body: JSON.stringify({
        textQuery: QUERY,
        includedType: "gym",
        pageSize: 20,
        locationRestriction: {
          rectangle: {
            low: { latitude: tile.south, longitude: tile.west },
            high: { latitude: tile.north, longitude: tile.east },
          },
        },
        ...(pageToken ? { pageToken } : {}),
      }),
    });
    if (!res.ok) throw new Error(`Text Search ${res.status}: ${await res.text()}`);
    const body = await res.json();
    places.push(...(body.places ?? []));
    pageToken = body.nextPageToken;
    // Google needs a moment before a page token is valid.
    if (pageToken) await new Promise((r) => setTimeout(r, 1500));
  } while (pageToken);
  return places;
}

function split(tile) {
  const midLat = (tile.south + tile.north) / 2;
  const midLng = (tile.west + tile.east) / 2;
  return [
    { south: tile.south, north: midLat, west: tile.west, east: midLng },
    { south: tile.south, north: midLat, west: midLng, east: tile.east },
    { south: midLat, north: tile.north, west: tile.west, east: midLng },
    { south: midLat, north: tile.north, west: midLng, east: tile.east },
  ];
}

const queue = [];
for (let lat = REGION.south; lat < REGION.north; lat += START_TILE_DEG) {
  for (let lng = REGION.west; lng < REGION.east; lng += START_TILE_DEG) {
    queue.push({
      south: lat,
      north: Math.min(lat + START_TILE_DEG, REGION.north),
      west: lng,
      east: Math.min(lng + START_TILE_DEG, REGION.east),
    });
  }
}

const found = new Map(); // place ID -> display name (for the log only)
let closed = 0;
while (queue.length > 0) {
  const tile = queue.shift();
  const places = await searchTile(tile);
  // A full result set may be truncated: split the tile and search again.
  if (places.length >= PAGE_CAP && tile.north - tile.south > MIN_TILE_DEG) {
    queue.push(...split(tile));
    continue;
  }
  for (const p of places) {
    const name = p.displayName?.text ?? "";
    const lat = p.location?.latitude;
    const lng = p.location?.longitude;
    if (!BRAND.test(name) || lat === undefined || lng === undefined) continue;
    if (lat < REGION.south || lat > REGION.north || lng < REGION.west || lng > REGION.east) continue;
    if (p.businessStatus === "CLOSED_PERMANENTLY") {
      closed += 1;
      continue;
    }
    found.set(p.id, name);
  }
}

const ids = [...found.keys()].sort();
const today = new Date().toISOString().slice(0, 10);
const sql = `-- 24 Hour Fitness clubs in Southern California, by Google place ID.
-- Generated by scripts/fetch-24hf-socal.mjs on ${today}: ${ids.length} clubs.
-- Region: lat ${REGION.south} to ${REGION.north}, lng ${REGION.west} to ${REGION.east}
-- (Mexican border to just north of Santa Clarita, Arizona border to Oxnard).
--
-- Only place IDs are stored. Google's terms allow keeping place IDs
-- indefinitely, but not business names, addresses or coordinates.
-- "brand" and "region" are our own labels, not Google content.

create table if not exists public.partner_gyms (
  place_id text primary key check (char_length(place_id) between 1 and 300),
  brand text not null,
  region text not null,
  added_at timestamptz not null default now()
);

alter table public.partner_gyms enable row level security;

drop policy if exists partner_gyms_select_all on public.partner_gyms;
create policy partner_gyms_select_all on public.partner_gyms
  for select to authenticated using (true);

insert into public.partner_gyms (place_id, brand, region) values
${ids.map((id) => `  ('${id.replace(/'/g, "''")}', '24 Hour Fitness', 'socal')`).join(",\n")}
on conflict (place_id) do nothing;
`;

writeFileSync(output, sql);
console.log(`${ids.length} clubs (${closed} permanently closed skipped), ${calls} API calls. Wrote ${output}`);
for (const [id, name] of [...found.entries()].sort((a, b) => a[1].localeCompare(b[1]))) {
  console.log(`  ${name}  ${id}`);
}
